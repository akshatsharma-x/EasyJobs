/**
 * Wipro — careers.wipro.com (SAP SuccessFactors RMK, "SearchResultsUnify").
 *
 * The search page loads jobs from POST /services/recruiting/v1/jobs, which robots.txt disallows
 * (`Disallow: /services/`), so this scraper uses the allowed path instead:
 *   - list:   GET https://careers.wipro.com/sitemap.xml  → ~7k /job/<City>-<TITLE>-<ISO3>-<postal>/<postingId>/
 *             India is selected from the ISO-3 country token in the slug ("…-IND-560035").
 *   - detail: GET the job page (unknown ids only) → "Posting Start Date" (M/D/YY), City,
 *             State/Province, description (itemprop="description"), "Mandatory Skills: …",
 *             "Experience: 8-10 Years". Closed postings render `jobErrMsg` and are skipped.
 *
 * Light records (known ids) are built from the slug alone, so title and location are derived
 * from the slug in BOTH cases — otherwise each run would flip the stored title/locations between
 * "Developer - L3" and "Developer L3". The page's own title is kept in extra.pageTitle.
 * The sitemap is regenerated by the site every few days, so brand-new postings can lag.
 */
import type { RawJob } from "@easyjobs/contract";
import {
  buildRawJob, cleanInline, defineCareerSite, detectJobType, htmlToText, isIndiaLocation, parseExperienceYears,
  postedAtFrom, type CompanyInfo, type SiteContext,
} from "../lib";
import { fetchRmkSitemap, parseRmkJobPage, SkipMemo, slugWords, type RmkJobPage, type RmkSitemapEntry } from "./_successfactors";

export const WIPRO: CompanyInfo = {
  slug: "wipro",
  name: "Wipro",
  domain: "wipro.com",
  careersUrl: "https://careers.wipro.com/",
};

const ORIGIN = "https://careers.wipro.com";
const MULTI_WORD_CITIES = ["greater noida", "gandhi nagar", "new delhi", "navi mumbai", "greater mumbai", "sri city"];
/** ISO-3 codes that appear as the country token in Wipro slugs (a title acronym such as "SAP" must not match). */
const COUNTRY_CODES = new Set(
  ("IND USA TWN GBR ROU JPN CHN PHL POL MEX SAU PRT CAN SGP HUN NLD LUX AUS QAT BRA VNM SWE MYS PER AUT CHE DEU TUR " +
    "CZE DNK ARE ESP IDN FRA ITA BEL IRL NZL ZAF EGY ISR KOR THA HKG FIN NOR ARG CHL COL CRI SVK BGR LKA BHR KWT OMN " +
    "NGA KEN MAR GRC SRB HRV UKR EST LVA LTU URY ECU PAN GTM DOM").split(" "),
);

export interface WiproSlug {
  city: string | null;
  title: string;
  /** ISO-3 country code from the slug ("IND"), null if absent. */
  country: string | null;
  postal: string | null;
}

/** "Bengaluru-DEVELOPER-L3-IND-560035" → { city: "Bengaluru", title: "DEVELOPER L3", country: "IND", postal: "560035" }. */
export function parseWiproSlug(slug: string): WiproSlug {
  const parts = slug.split("-").filter((p) => p.length > 0);
  let countryIdx = -1;
  for (let i = parts.length - 1; i >= 1; i--) {
    const tail = parts.slice(i + 1);
    if (COUNTRY_CODES.has(parts[i]!) && tail.length <= 2 && tail.every((t) => /^[0-9A-Z]{1,8}$/.test(t) && /\d/.test(t))) {
      countryIdx = i;
      break;
    }
  }
  const head = countryIdx >= 0 ? parts.slice(0, countryIdx) : parts;
  const lower = head.map((p) => p.toLowerCase());
  const multi = MULTI_WORD_CITIES.find((c) => lower.slice(0, c.split(" ").length).join(" ") === c);
  const cityLen = multi ? multi.split(" ").length : 1;
  const city = head.length > cityLen ? head.slice(0, cityLen).join(" ") : null;
  return {
    city,
    title: slugWords((city ? head.slice(cityLen) : head).join("-")),
    country: countryIdx >= 0 ? parts[countryIdx]! : null,
    postal: countryIdx >= 0 ? (parts.slice(countryIdx + 1).join("-") || null) : null,
  };
}

export function isWiproIndia(entry: RmkSitemapEntry): boolean {
  const s = parseWiproSlug(entry.slug);
  // A slug without a country token is kept only when its city prefix is an Indian city.
  return s.country === "IND" || (s.country === null && isIndiaLocation(s.city));
}

export interface WiproDetail {
  page: RmkJobPage;
}

const BOILERPLATE = /^(wipro limited \(nyse|reinvent your world)/i;

/** Cuts the HTML at the block element that starts the corporate outro, when it's inlined in the JD. */
function cutAtOutro(html: string): string {
  const m = /Reinvent your world\./i.exec(html);
  if (!m || m.index < 200) return html;
  const before = html.slice(0, m.index);
  const blockStart = Math.max(before.lastIndexOf("<p"), before.lastIndexOf("<div"), before.lastIndexOf("<span"));
  return html.slice(0, blockStart > 0 ? blockStart : m.index);
}

/** The job-specific description block(s), without the corporate intro/outro. */
export function wiproDescription(page: RmkJobPage): string | null {
  const blocks = page.descriptions.filter((d) => !BOILERPLATE.test((htmlToText(d) ?? "").trim()));
  const chosen = blocks.length > 0 ? blocks : [...page.descriptions].sort((a, b) => b.length - a.length).slice(0, 1);
  if (chosen.length === 0) return null;
  const html = cutAtOutro(chosen.join("\n"))
    .replace(/\r\n?/g, "\n")
    .replace(/\u034f/g, "");
  return htmlToText(html) ? html : null;
}

/** "Mandatory Skills: Fullstack Java Enterprise . Experience: 3-5 Years ." */
export function wiproSkillsAndExperience(text: string | null): { skills: string[]; experienceRaw: string | null } {
  if (!text) return { skills: [], experienceRaw: null };
  const flat = text.replace(/\s+/g, " ");
  const skills = /Mandatory Skills\s*:\s*(.+?)\s*(?:\.\s|\.$|Experience\s*:|$)/i.exec(flat)?.[1];
  const exp = /Experience\s*:\s*([0-9]+\s*(?:-|–|to)\s*[0-9]+\s*(?:Years?|Yrs?)|[0-9]+\s*\+?\s*(?:Years?|Yrs?)|Fresher[s]?)/i.exec(flat)?.[1];
  return {
    skills: skills ? skills.split(/\s*[,;|]\s*/).map((s) => cleanInline(s)).filter((s) => s.length > 1 && s.length <= 60) : [],
    experienceRaw: exp ? cleanInline(exp) : null,
  };
}

export function mapWiproJob(entry: RmkSitemapEntry, detail: WiproDetail | null): RawJob {
  const slug = parseWiproSlug(entry.slug);
  const page = detail?.page ?? null;
  const descriptionHtml = page ? wiproDescription(page) : null;
  const text = htmlToText(descriptionHtml);
  const { skills, experienceRaw } = wiproSkillsAndExperience(text);
  const years = parseExperienceYears(experienceRaw);
  const contract = /\bcontract\b/i.test(slug.title);
  return buildRawJob(WIPRO, {
    sourceJobId: entry.id,
    title: slug.title,
    sourceUrl: entry.url,
    applyUrl: entry.url,
    locations: [slug.city ? `${slug.city}, India` : "India"],
    descriptionHtml,
    descriptionText: text,
    postedAt: page ? postedAtFrom(page.fields["Posting Start Date"], { dayFirst: false }) : null,
    jobType: contract ? "contract" : detectJobType({ title: slug.title }),
    employmentTypeRaw: contract ? "Contract" : null,
    experienceRaw,
    experienceMin: years?.min ?? null,
    experienceMax: years?.max ?? null,
    skills,
    extra: {
      pageTitle: page?.title,
      city: page?.fields.City,
      state: page?.fields["State/Province"],
      postal: slug.postal,
      /** Wipro band ("L1"–"L5") as written in the title. */
      band: /\bL([1-5])\b/.exec(slug.title)?.[0],
      canonicalUrl: page?.canonicalUrl && !/\/job\/\/+$/.test(page.canonicalUrl) ? page.canonicalUrl : undefined,
    },
  });
}

/** Postings dropped after a detail fetch (closed) — see SkipMemo. */
export const wiproSkipped = new SkipMemo();

export const wipro = defineCareerSite<RmkSitemapEntry, WiproDetail>({
  company: WIPRO,
  name: "Wipro Careers",
  intervalMinutes: 60,
  endpointType: "sitemap.xml + job pages (SuccessFactors RMK HTML)",
  async *list(ctx: SiteContext) {
    const entries = await fetchRmkSitemap(ctx, ORIGIN);
    const india = entries.filter(isWiproIndia);
    ctx.reportTotal(india.length);
    yield* india;
  },
  idOf: (e) => e.id,
  keep: (e) => !wiproSkipped.has(e.id),
  async detail(e, ctx) {
    const html = await ctx.http.text(e.url, { headers: { accept: "text/html" } });
    return { page: parseRmkJobPage(html) };
  },
  toRawJob(e, detail, ctx) {
    if (detail?.page.closed) {
      wiproSkipped.add(e.id);
      return null;
    }
    // Unknown job whose detail fetch failed or was deferred: retry next run rather than store it without details.
    if (!detail && !(ctx.isKnown?.(e.id, WIPRO.slug) ?? false)) return null;
    return mapWiproJob(e, detail);
  },
});
